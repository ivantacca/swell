def body(svg):
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    return re.sub(r"\s+", " ", re.sub(r">\s+<", "><", inner.strip())).replace(
        '" />', '"/>'
    )


def main(directory):
    directory = Path(directory)
    categories = []
    for name, icon, names in CATEGORIES:
        symbols = []
        for symbol in names.split():
            path = directory / f"{symbol}.svg"
            if not path.exists():
                sys.exit(f"no such Iconoir icon: {symbol}")
            keywords = f"{symbol.replace('-', ' ')} {name.lower()}"
            symbols.append([symbol, keywords, body(path.read_text())])
        categories.append({"name": name, "icon": icon, "symbols": symbols})
    out = Path(__file__).resolve().parent.parent / "app/content/symbol-data.mjs"
    out.write_text(
        "/* This Source Code Form is subject to the terms of the Mozilla Public\n"
        " * License, v. 2.0. If a copy of the MPL was not distributed with this\n"
        " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */\n\n"
        "// Generated by tools/build-symbols.py from Iconoir (MIT, see\n"
        "// icons/LICENSE-iconoir). Each symbol is [name, keywords, svg markup].\n"
        "export const SYMBOL_CATEGORIES = "
        + json.dumps(categories, indent=1, ensure_ascii=False)
        + ";\n"
    )
    print(sum(len(c["symbols"]) for c in categories), "symbols,", out.stat().st_size, "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
